def summarize_drug_info(med_info):
  if med_info is None:
    return None
  if med_info["side_effects"] is None:
    return f"Aucune information sur les effets secondaires n'est disponible pour {med_info['name']}."
  prompt=f"""resume les informations sur les effets indesirables '{med_info["side_effects"]}' du medicament '{med_info['name']}' en 4 phrases en français simple, sans jargon médical. Base-toi uniquement sur le texte suivant, n'ajoute aucune information qui n'y figure pas"""
  response=client.models.generate_content(
        model="gemini-3.1-flash-lite",
        contents=prompt
   )

  return response.text

from google.genai import types
from google import genai

def ask_agent(question):

    config = types.GenerateContentConfig(tools=[get_drug_label])

    response =client.models.generate_content (
        model="gemini-3.1-flash-lite",
        contents=question ,
        config=config
    )

    if response.function_calls:

        call = response.function_calls[0]
        drug_name_found = call.args["drug_name"]
        print(f" L'agent a identifié le médicament : {drug_name_found}")

        raw_data = get_drug_label(drug_name_found)
        med_info = extract_drug_info(raw_data)

        return summarize_drug_info(med_info)

    else:
        return response.text
